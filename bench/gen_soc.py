#!/usr/bin/env python3
"""bench/gen_soc.py N [CYCLES] - a synthetic SoC-shaped design for the tool benchmarks.

N cores, each a small pipeline: an LFSR stimulus, a 4-state FSM, an ALU with a
case decode, a 16-entry register file, an accumulator, and a two-flop
synchronizer into a second clock domain. Hierarchy is soc_top -> cluster ->
core -> alu, so waveform scopes, coverage files and lint/DFT walks all see a
realistic instance tree. The testbench prints a checksum and finishes after
CYCLES cycles of the fast clock (default 2000).

    python3 bench/gen_soc.py 64 > soc.sv && msim soc.sv -top soc_tb
"""
import sys

n = int(sys.argv[1]) if len(sys.argv) > 1 else 64
cycles = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
per_cluster = 8
clusters = (n + per_cluster - 1) // per_cluster

print(f"""// Generated by bench/gen_soc.py {n} {cycles}: {n} cores in {clusters} clusters.
module alu(input logic [2:0] op, input logic [31:0] a, b, output logic [31:0] y, output logic z);
  always_comb begin
    case (op)
      3'd0: y = a + b;
      3'd1: y = a - b;
      3'd2: y = a & b;
      3'd3: y = a | b;
      3'd4: y = a ^ b;
      3'd5: y = a << b[4:0];
      3'd6: y = a >> b[4:0];
      default: y = {{a[15:0], b[15:0]}};
    endcase
    z = (y == 32'd0);
  end
endmodule

module core #(parameter int SEED = 1) (input logic clk, input logic sclk, input logic rst_n,
                                       output logic [31:0] acc, output logic [7:0] slow);
  logic [31:0] lfsr, opa, opb, y;
  logic [1:0] st;
  logic [2:0] op;
  logic z;
  logic [31:0] rf [0:15];
  logic [3:0] wa;
  logic tick, s1, s2;
  alu u_alu(.op(op), .a(opa), .b(opb), .y(y), .z(z));
  always_ff @(posedge clk or negedge rst_n)
    if (!rst_n) begin
      lfsr <= 32'(SEED) | 32'h1; st <= 2'd0; acc <= 32'd0; wa <= 4'd0; tick <= 1'b0;
      for (int i = 0; i < 16; i++) rf[i] <= 32'(i * SEED);
    end else begin
      lfsr <= {{lfsr[30:0], lfsr[31] ^ lfsr[21] ^ lfsr[1] ^ lfsr[0]}};
      case (st)
        2'd0: st <= lfsr[0] ? 2'd1 : 2'd0;
        2'd1: st <= 2'd2;
        2'd2: st <= z ? 2'd0 : 2'd3;
        default: st <= 2'd0;
      endcase
      if (st == 2'd2) begin
        rf[wa] <= y;
        wa <= wa + 4'd1;
        acc <= acc + y;
      end
      if (wa == 4'd15) tick <= ~tick;
    end
  always_comb begin
    op = lfsr[4:2];
    opa = lfsr;
    opb = rf[lfsr[8:5]];
  end
  // tick crosses into the slow clock domain through two flops.
  always_ff @(posedge sclk) s1 <= tick;
  always_ff @(posedge sclk) s2 <= s1;
  always_ff @(posedge sclk or negedge rst_n)
    if (!rst_n) slow <= 8'd0;
    else if (s2) slow <= slow + 8'd1;
endmodule
""")

print("module cluster #(parameter int BASE = 0) (input logic clk, sclk, rst_n, output logic [31:0] sum);")
print(f"  logic [31:0] acc [{per_cluster}];")
print(f"  logic [7:0] slow [{per_cluster}];")
for i in range(per_cluster):
    print(f"  core #(.SEED(BASE * {per_cluster} + {i} + 1)) c{i}(.clk(clk), .sclk(sclk), .rst_n(rst_n), .acc(acc[{i}]), .slow(slow[{i}]));")
print("  always_comb begin")
print("    sum = 32'd0;")
for i in range(per_cluster):
    print(f"    sum = sum ^ acc[{i}] ^ {{24'd0, slow[{i}]}};")
print("  end")
print("endmodule\n")

print("module soc_top(input logic clk, sclk, rst_n, output logic [31:0] chk);")
print(f"  logic [31:0] s [{clusters}];")
for c in range(clusters):
    print(f"  cluster #(.BASE({c})) k{c}(.clk(clk), .sclk(sclk), .rst_n(rst_n), .sum(s[{c}]));")
print("  always_comb begin")
print("    chk = 32'd0;")
for c in range(clusters):
    print(f"    chk = chk + s[{c}];")
print("  end")
print("endmodule\n")

print(f"""module soc_tb;
  logic clk = 0, sclk = 0, rst_n = 0;
  logic [31:0] chk;
  soc_top dut(.clk(clk), .sclk(sclk), .rst_n(rst_n), .chk(chk));
  always #5 clk = ~clk;
  always #7 sclk = ~sclk;
  initial begin
    #12 rst_n = 1;
    #{cycles * 10} $display("checksum=%h", chk);
    $finish;
  end
endmodule""")
