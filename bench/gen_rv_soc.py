#!/usr/bin/env python3
"""bench/gen_rv_soc.py [--cpu ibex|picorv32|femtorv32] N [CYCLES] - a SoC of N real RISC-V cores.

Each core is an unmodified open-source RISC-V core in a small configuration,
with its own 1 KB RAM:
  ibex      lowRISC Ibex (Apache-2.0), RV32E without M, as in the Ibex
            benchmark (/mnt/project-files/opentitan-ibex: same file list)
  picorv32  PicoRV32 (ISC, Claire Xenia Wolf / YosysHQ), RV32I
  femtorv32 FemtoRV32 Quark (BSD-3-Clause, Bruno Levy), RV32I
The RAM
starts with a program that runs a xorshift32 generator from a per-core seed
and keeps a running sum and an iteration count in memory. After CYCLES
cycles the testbench checks that every core ran (count > 0), and prints
how many did, one checksum over all sums and counts, and the total loop
count (for CPI). The same checksum
from msim and from Verilator means both ran the same programs to the same
cycle. bench/gen_soc.py --core ibex|picorv32|femtorv32 calls this script; its default
(--core synthetic) stays the synthetic design.

Neither core is part of minisim; pass its sources too:

    curl -sLO https://raw.githubusercontent.com/YosysHQ/picorv32/main/picorv32.v
    python3 bench/gen_rv_soc.py --cpu picorv32 64 20000 > rvsoc.sv
    msim -compile picorv32.v rvsoc.sv -top rvsoc_tb
    verilator --binary -O3 --top-module rvsoc_tb picorv32.v rvsoc.sv

FemtoRV32 the same way, plus -DBENCH (else its shifter and x0 start as x), with
https://raw.githubusercontent.com/BrunoLevy/learn-fpga/master/FemtoRV/RTL/PROCESSOR/femtorv32_quark.v

For Ibex, the sources and options of the Ibex benchmark (its run_msim.sh)
with rvsoc.sv in place of tb_ibex.sv and -top rvsoc_tb.
"""
import sys

args = sys.argv[1:]
cpu = "ibex"
if len(args) >= 2 and args[0] in ("--cpu", "--core"):
    cpu, args = args[1], args[2:]
if cpu not in ("ibex", "picorv32", "femtorv32"):
    sys.exit("gen_rv_soc.py: --cpu ibex, picorv32 or femtorv32")
n = int(args[0]) if len(args) > 0 else 64
cycles = int(args[1]) if len(args) > 1 else 20000

# RV32I encodings (only what the program needs).
def r(f7, rs2, rs1, f3, rd, op=0x33): return (f7 << 25) | (rs2 << 20) | (rs1 << 15) | (f3 << 12) | (rd << 7) | op
def i(imm, rs1, f3, rd, op=0x13): return ((imm & 0xfff) << 20) | (rs1 << 15) | (f3 << 12) | (rd << 7) | op
def s(imm, rs2, rs1, f3=2): return ((imm >> 5 & 0x7f) << 25) | (rs2 << 20) | (rs1 << 15) | (f3 << 12) | ((imm & 0x1f) << 7) | 0x23
def lw(rd, imm, rs1=0): return i(imm, rs1, 2, rd, 0x03)
def addi(rd, rs1, imm): return i(imm, rs1, 0, rd)
def slli(rd, rs1, sh): return i(sh, rs1, 1, rd)
def srli(rd, rs1, sh): return i(sh, rs1, 5, rd)
def add(rd, a, b): return r(0, b, a, 0, rd)
def xor(rd, a, b): return r(0, b, a, 4, rd)
def sw(rs2, imm, rs1=0): return s(imm, rs2, rs1)
def jal(rd, off):
    o = off & 0x1fffff
    return ((o >> 20 & 1) << 31) | ((o >> 1 & 0x3ff) << 21) | ((o >> 11 & 1) << 20) | ((o >> 12 & 0xff) << 12) | (rd << 7) | 0x6f

SEED, SUM, COUNT = 0x100, 0x104, 0x108     # byte addresses of the data words
prog = [
    lw(1, SEED),           # x1 = seed
    addi(2, 0, 0),         # x2 = sum
    addi(3, 0, 0),         # x3 = count
    # loop: xorshift32
    slli(4, 1, 13), xor(1, 1, 4),
    srli(4, 1, 17), xor(1, 1, 4),
    slli(4, 1, 5), xor(1, 1, 4),
    add(2, 2, 1),
    addi(3, 3, 1),
    sw(2, SUM),
    sw(3, COUNT),
]
prog.append(jal(0, -4 * (len(prog) - 3)))   # back to the loop
words = 256

print(f"// Generated by bench/gen_rv_soc.py --cpu {cpu} {n} {cycles}: {n} {cpu} cores, each with 1 KB of RAM.")
print("module rv_core #(parameter logic [31:0] SEED = 1) (input logic clk, resetn, output logic [31:0] sum, count);")
print(f"  logic [31:0] mem [0:{words - 1}];")
if cpu == "picorv32":
    print("""  logic mem_valid, mem_instr, mem_ready;
  logic [31:0] mem_addr, mem_wdata, mem_rdata;
  logic [3:0] mem_wstrb;
  picorv32 #(.ENABLE_COUNTERS(0), .ENABLE_COUNTERS64(0), .CATCH_MISALIGN(0), .CATCH_ILLINSN(0))
    cpu(.clk(clk), .resetn(resetn), .mem_valid(mem_valid), .mem_instr(mem_instr), .mem_ready(mem_ready),
        .mem_addr(mem_addr), .mem_wdata(mem_wdata), .mem_wstrb(mem_wstrb), .mem_rdata(mem_rdata),
        .pcpi_wr(1'b0), .pcpi_rd(32'd0), .pcpi_wait(1'b0), .pcpi_ready(1'b0), .irq(32'd0), .trace_valid(), .trace_data(),
        .mem_la_read(), .mem_la_write(), .mem_la_addr(), .mem_la_wdata(), .mem_la_wstrb(), .pcpi_valid(), .pcpi_insn(),
        .pcpi_rs1(), .pcpi_rs2(), .eoi(), .trap());
  always_ff @(posedge clk) begin
    mem_ready <= 1'b0;
    if (mem_valid && !mem_ready) begin
      mem_rdata <= mem[mem_addr[9:2]];
      if (mem_wstrb[0]) mem[mem_addr[9:2]][7:0] <= mem_wdata[7:0];
      if (mem_wstrb[1]) mem[mem_addr[9:2]][15:8] <= mem_wdata[15:8];
      if (mem_wstrb[2]) mem[mem_addr[9:2]][23:16] <= mem_wdata[23:16];
      if (mem_wstrb[3]) mem[mem_addr[9:2]][31:24] <= mem_wdata[31:24];
      mem_ready <= 1'b1;
    end
  end""")
elif cpu == "femtorv32":
    print("""  logic [31:0] mem_addr, mem_wdata, mem_rdata;
  logic [3:0] mem_wmask;
  logic mem_rstrb;
  FemtoRV32 cpu(.clk(clk), .reset(resetn), .mem_addr(mem_addr), .mem_wdata(mem_wdata), .mem_wmask(mem_wmask),
                .mem_rdata(mem_rdata), .mem_rstrb(mem_rstrb), .mem_rbusy(1'b0), .mem_wbusy(1'b0));
  always_ff @(posedge clk) begin
    if (mem_rstrb) mem_rdata <= mem[mem_addr[9:2]];
    if (mem_wmask[0]) mem[mem_addr[9:2]][7:0] <= mem_wdata[7:0];
    if (mem_wmask[1]) mem[mem_addr[9:2]][15:8] <= mem_wdata[15:8];
    if (mem_wmask[2]) mem[mem_addr[9:2]][23:16] <= mem_wdata[23:16];
    if (mem_wmask[3]) mem[mem_addr[9:2]][31:24] <= mem_wdata[31:24];
  end""")
else:
    print("""  import ibex_pkg::*;
  logic instr_req, instr_rvalid, data_req, data_rvalid, data_we;
  logic [31:0] instr_addr, instr_rdata, data_addr, data_wdata, data_rdata;
  logic [3:0] data_be;
  always_ff @(posedge clk) begin
    instr_rvalid <= instr_req;
    if (instr_req) instr_rdata <= mem[instr_addr[9:2]];
    data_rvalid <= data_req;
    if (data_req) begin
      if (data_we) begin
        if (data_be[0]) mem[data_addr[9:2]][7:0] <= data_wdata[7:0];
        if (data_be[1]) mem[data_addr[9:2]][15:8] <= data_wdata[15:8];
        if (data_be[2]) mem[data_addr[9:2]][23:16] <= data_wdata[23:16];
        if (data_be[3]) mem[data_addr[9:2]][31:24] <= data_wdata[31:24];
      end else data_rdata <= mem[data_addr[9:2]];
    end
  end
  ibex_top #(.RV32E(1'b1), .RV32M(RV32MNone)) cpu (
    .clk_i(clk), .rst_ni(resetn), .test_en_i(1'b0),
    .ram_cfg_icache_tag_i('0), .ram_cfg_icache_tag_o(), .ram_cfg_icache_data_i('0), .ram_cfg_icache_data_o(),
    .cheriot_enable_i(IbexMuBiOff), .hart_id_i(32'd0), .boot_addr_i(32'h0), .trvk_heap_base_addr_i(32'h0),
    .instr_req_o(instr_req), .instr_gnt_i(instr_req), .instr_rvalid_i(instr_rvalid), .instr_addr_o(instr_addr),
    .instr_rdata_i(instr_rdata), .instr_rdata_intg_i(7'd0), .instr_err_i(1'b0),
    .data_req_o(data_req), .data_gnt_i(data_req), .data_rvalid_i(data_rvalid), .data_we_o(data_we),
    .data_be_o(data_be), .data_addr_o(data_addr), .data_wdata_o(data_wdata), .data_wdata_intg_o(), .data_tag_o(),
    .data_rdata_i(data_rdata), .data_rdata_intg_i(7'd0), .data_tag_i(1'b0), .data_err_i(1'b0),
    .trvk_revbm_req_o(), .trvk_revbm_gnt_i(1'b0), .trvk_revbm_rvalid_i(1'b0), .trvk_revbm_addr_o(),
    .trvk_revbm_rdata_i(32'd0), .trvk_revbm_rdata_intg_i(7'd0), .trvk_revbm_err_i(1'b0),
    .irq_software_i(1'b0), .irq_timer_i(1'b0), .irq_external_i(1'b0), .irq_fast_i(15'd0), .irq_nm_i(1'b0),
    .scramble_key_valid_i(1'b0), .scramble_key_i('0), .scramble_nonce_i('0), .scramble_req_o(),
    .debug_req_i(1'b0), .crash_dump_o(), .double_fault_seen_o(),
    .fetch_enable_i(IbexMuBiOn), .alert_minor_o(), .alert_major_internal_o(), .alert_major_bus_o(),
    .core_sleep_o(), .mcounteren_writable_i(1'b0), .scan_rst_ni(1'b1));""")
print("""  assign sum = mem[""" + str(SUM // 4) + """];
  assign count = mem[""" + str(COUNT // 4) + """];
  initial begin
    for (int k = 0; k < """ + str(words) + """; k++) mem[k] = 32'd0;""")
for k, w in enumerate(prog):
    print(f"    mem[{k}] = 32'h{w:08x};")
print(f"    mem[{SEED // 4}] = SEED;")
print("""  end
endmodule
""")

print("module rvsoc_tb;")
print("  logic clk = 0, resetn = 0;")
print(f"  logic [31:0] sum [{n}], count [{n}];")
for c in range(n):
    seed = (0x9E3779B9 * (c + 1)) & 0xffffffff or 1
    print(f"  rv_core #(.SEED(32'h{seed:08x})) c{c}(.clk(clk), .resetn(resetn), .sum(sum[{c}]), .count(count[{c}]));")
print(f"""  always #5 clk = ~clk;
  initial begin
    int ran;
    longint iters;
    logic [31:0] chk;
    #20 resetn = 1;
    #{cycles * 10};
    ran = 0; iters = 0; chk = 32'd0;
    for (int c = 0; c < {n}; c++) begin
      if (count[c] != 0) ran++;
      iters += count[c];
      chk = (chk ^ sum[c]) + count[c];
    end
    $display("cores_ran=%0d/{n} checksum=%h loops=%0d", ran, chk, iters);
    $finish;
  end
endmodule""")
