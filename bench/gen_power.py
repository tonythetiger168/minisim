#!/usr/bin/env python3
"""bench/gen_power.py - a gate netlist and its activity for timing mpower.

  gen_power.py <cells> <out-prefix> [cycles]

Writes <out>.v (module big: a few blocks of random logic over the cells of
tests/power/pw.lib, a flop on about one cell in five) and <out>.vcd, the
waveform of a zero-delay simulation of it done here, so no simulator is
needed. The same seed gives the same files.
"""
import random
import sys


def main():
    n = int(sys.argv[1])
    out = sys.argv[2]
    cycles = int(sys.argv[3]) if len(sys.argv) > 3 else 40
    rnd = random.Random(1)
    nin = 16
    blocks = max(1, min(8, n // 500))
    # cells: (type, block, inputs, output); nets are numbers, 0..nin-1 are inputs
    cells = []
    drivers = list(range(nin))
    flops = []
    for i in range(n):
        net = nin + i
        k = rnd.random()
        pick = lambda: drivers[rnd.randrange(max(0, len(drivers) - 400), len(drivers))]
        if k < 0.2:
            cells.append(("DFF", i % blocks, [pick()], net))
            flops.append(len(cells) - 1)
        elif k < 0.4:
            cells.append(("INV", i % blocks, [pick()], net))
        elif k < 0.75:
            cells.append(("NAND2", i % blocks, [pick(), pick()], net))
        else:
            cells.append(("XOR2", i % blocks, [pick(), pick()], net))
        drivers.append(net)
    total = nin + n
    name = lambda x: "in[%d]" % x if x < nin else "n%d" % x

    with open(out + ".v", "w") as f:
        f.write("// generated by bench/gen_power.py %d\n" % n)
        for b in range(blocks):
            f.write("module blk%d(input clk, input [%d:0] w, output [%d:0] o);\n" % (b, total - 1, total - 1))
            for i, (t, blk, ins, o) in enumerate(cells):
                if blk != b:
                    continue
                if t == "DFF":
                    f.write("  DFF c%d(.D(w[%d]), .CK(clk), .Q(o[%d]));\n" % (i, ins[0], o))
                elif t == "INV":
                    f.write("  INV c%d(.A(w[%d]), .Y(o[%d]));\n" % (i, ins[0], o))
                else:
                    f.write("  %s c%d(.A(w[%d]), .B(w[%d]), .Y(o[%d]));\n" % (t, i, ins[0], ins[1], o))
            f.write("endmodule\n")
        f.write("module big(input clk, input [%d:0] in, output [7:0] out);\n" % (nin - 1))
        f.write("  wire [%d:0] w;\n" % (total - 1))
        f.write("  assign w[%d:0] = in;\n" % (nin - 1))
        for b in range(blocks):
            f.write("  blk%d u%d(.clk(clk), .w(w), .o(w));\n" % (b, b))
        f.write("  assign out = w[%d:%d];\n" % (total - 1, total - 8))
        f.write("endmodule\n")

    # zero-delay simulation: flops sample on the rising edge, logic settles in net order
    val = [0] * total
    ids = {}

    def ident(k):
        s = ""
        k += 1
        while k:
            k, r = divmod(k - 1, 94)
            s += chr(33 + r)
        return s

    with open(out + ".vcd", "w") as f:
        f.write("$timescale 1ns $end\n$scope module tb $end\n$scope module big $end\n")
        f.write("$var wire 1 %s clk $end\n" % ident(0))
        f.write("$var wire %d %s in $end\n" % (nin, ident(1)))
        f.write("$var wire %d %s w $end\n" % (total, ident(2)))
        f.write("$upscope $end\n$upscope $end\n$enddefinitions $end\n")

        def settle():
            for (t, blk, ins, o) in cells:
                if t == "INV":
                    val[o] = 1 - val[ins[0]]
                elif t == "NAND2":
                    val[o] = 1 - (val[ins[0]] & val[ins[1]])
                elif t == "XOR2":
                    val[o] = val[ins[0]] ^ val[ins[1]]

        def dump(t, clk):
            f.write("#%d\n%d%s\n" % (t, clk, ident(0)))
            f.write("b%s %s\n" % ("".join(str(val[i]) for i in range(nin - 1, -1, -1)), ident(1)))
            f.write("b%s %s\n" % ("".join(str(val[i]) for i in range(total - 1, -1, -1)), ident(2)))

        settle()
        dump(0, 0)
        for c in range(cycles):
            # inputs change while the clock is low; the second half of the run is quieter
            for i in range(nin):
                if rnd.random() < (0.4 if c < cycles // 2 else 0.05):
                    val[i] ^= 1
            nxt = [(cells[k][3], val[cells[k][2][0]]) for k in flops]
            for o, v in nxt:
                val[o] = v
            settle()
            dump(c * 10 + 5, 1)
            f.write("#%d\n0%s\n" % (c * 10 + 10, ident(0)))


if __name__ == "__main__":
    main()
