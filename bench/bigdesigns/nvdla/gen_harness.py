#!/usr/bin/env python3
"""gen_harness.py VNV_nvdla.h outdir
Runs NVDLA's own Verilator trace player (verif/verilator/nvdla.cpp) unchanged against msim.
From the port list in a Verilator-generated VNV_nvdla.h it writes:
  VNV_nvdla.h, verilated.h, verilated_vcd_c.h  stand-ins, so nvdla.cpp compiles as is
  nv_glue.cpp   runs nvdla.cpp's main() in a thread; every dla->eval() hands the inputs to
                the SV testbench and waits for the outputs (one DPI call per eval)
  tb_nvdla.sv   applies the inputs, waits 1 time unit, returns the outputs"""
import re, sys, os
hdr, out = sys.argv[1], sys.argv[2]
ports = []  # (dir, name, width)
for d, n, hi in re.findall(r'VL_(IN|OUT)(?:8|16|64|W)?\(&(\w+),(\d+),0', open(hdr).read()):
    ports.append((d, n, int(hi) + 1))
def ctype(w): return 'CData' if w <= 8 else 'SData' if w <= 16 else 'IData' if w <= 32 else 'QData' if w <= 64 else None
os.makedirs(out, exist_ok=True)
W = open(f'{out}/VNV_nvdla.h', 'w')
W.write('#pragma once\n#include <cstdint>\ntypedef uint8_t CData; typedef uint16_t SData; typedef uint32_t IData; typedef uint64_t QData;\n'
        'class VerilatedVcdC;\nstruct VNV_nvdla {\n')
for d, n, w in ports:
    W.write(f'  {ctype(w)} {n};\n' if ctype(w) else f'  IData {n}[{(w + 31) // 32}];\n')
W.write('  VNV_nvdla() : ' + ', '.join(f'{n}()' for _, n, _ in ports) + ' {}\n')
W.write('  void eval();\n  void trace(VerilatedVcdC*, int) {}\n};\n')
W.close()
open(f'{out}/verilated.h', 'w').write('#pragma once\nnamespace Verilated { inline void commandArgs(int, const char**) {} }\n')
open(f'{out}/verilated_vcd_c.h', 'w').write('#pragma once\nclass VerilatedVcdC { public: void dump(unsigned long) {} void open(const char*) {} void close() {} };\n')
def words(w): return (w + 31) // 32
outs = [p for p in ports if p[0] == 'OUT']; ins = [p for p in ports if p[0] == 'IN']
G = open(f'{out}/nv_glue.cpp', 'w')
G.write('''// generated by gen_harness.py: drives NVDLA's nvdla.cpp trace player from an SV testbench
#include <thread>
#include <mutex>
#include <condition_variable>
#include <cstring>
#include <cstdlib>
#include <unistd.h>
#include "svdpi.h"
#define main nvdla_main
#include "nvdla.cpp"
#undef main
static std::mutex mu; static std::condition_variable cv;
static int turn = 0;             // 0: C++ runs, 1: SV runs
static bool finished = false; static int exit_code = 0;
static VNV_nvdla* the_dla;
void VNV_nvdla::eval() {
  std::unique_lock<std::mutex> l(mu);
  the_dla = this; turn = 1; cv.notify_all();
  cv.wait(l, [] { return turn == 0; });
}
template <class T> static void cp_out(T& d, const svBitVecVal* s) { T v = 0; memcpy(&v, s, sizeof(T)); d = v; }
static void cp_outw(IData* d, const svBitVecVal* s, int n) { memcpy(d, s, n * 4); }
extern "C" int nv_step(''')
args = [f'const svBitVecVal* o_{n}' for _, n, _ in outs] + [f'svBitVecVal* i_{n}' for _, n, _ in ins]
G.write(', '.join(args) + ''') {
  static std::thread* th;
  std::unique_lock<std::mutex> l(mu);
  if (!th) {
    const char* tf = getenv("NV_TRACE"); static const char* argv[] = {"nvdla", nullptr, nullptr}; argv[1] = tf ? tf : "trace.bin";
    th = new std::thread([] { int rc = nvdla_main(2, argv, nullptr); std::lock_guard<std::mutex> g(mu); exit_code = rc; finished = true; turn = 1; cv.notify_all(); });
  } else {
''')
for _, n, w in outs:
    G.write(f'    cp_outw(the_dla->{n}, o_{n}, {words(w)});\n' if w > 64 else f'    cp_out(the_dla->{n}, o_{n});\n')
G.write('''    turn = 0; cv.notify_all();
  }
  cv.wait(l, [] { return turn == 1; });
  if (finished) return 0;
''')
for _, n, w in ins:
    if w > 64: G.write(f'  memcpy(i_{n}, the_dla->{n}, {words(w) * 4});\n')
    else: G.write(f'  {{ uint32_t t[2] = {{0, 0}}; memcpy(t, &the_dla->{n}, sizeof(the_dla->{n})); memcpy(i_{n}, t, {words(w) * 4}); }}\n')
G.write('  return 1;\n}\nextern "C" int nv_exit_code() { return exit_code; }\n')
G.close()
T = open(f'{out}/tb_nvdla.sv', 'w')
T.write('// generated by gen_harness.py\nmodule tb_nvdla;\n')
for d, n, w in ports: T.write(f'  logic [{w - 1}:0] {n};\n')
dargs = [f'input bit [{w - 1}:0] o_{n}' for _, n, w in outs] + [f'output bit [{w - 1}:0] i_{n}' for _, n, w in ins]
T.write('  import "DPI-C" function int nv_step(' + ', '.join(dargs) + ');\n  import "DPI-C" function int nv_exit_code();\n')
T.write('  NV_nvdla dut (' + ', '.join(f'.{n}({n})' for _, n, _ in ports) + ');\n')
tmp = [f'b_{n}' for _, n, _ in ins]
for d, n, w in ins: T.write(f'  bit [{w - 1}:0] b_{n};\n')
T.write('''  initial begin
    longint evals = 0;
    while (nv_step(''' + ', '.join([n for _, n, _ in outs] + tmp) + ''')) begin
''')
for _, n, _ in ins: T.write(f'      {n} = b_{n};\n')
T.write('''      #1; evals++;
    end
    $display("tb_nvdla: trace player exited with %0d after %0d evals", nv_exit_code(), evals);
    $finish;
  end
endmodule
''')
T.close()
print(len(ins), 'inputs', len(outs), 'outputs')
