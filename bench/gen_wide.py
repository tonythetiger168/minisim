#!/usr/bin/env python3
"""bench/gen_wide.py - write bench/wide.sv: N independent lanes (default 256).

Each lane is an LFSR, a 4-stage mixing pipeline of continuous assigns, and an
accumulator, all on one clock. Lanes only meet in the final checksum, so the
work per clock edge is wide and independent: the case where multi-core
simulation (msim -threads) can help. Usage: gen_wide.py [lanes] > wide.sv
"""
import sys

n = int(sys.argv[1]) if len(sys.argv) > 1 else 256
L = []
L.append(f"// bench/wide.sv - generated by bench/gen_wide.py {n}. {n} independent lanes.")
L.append("// Each lane: a 32-bit LFSR, four continuous-assign mixing stages, an accumulator.")
L.append("// END_TIME is 10 per cycle (default 200000 = 20k cycles).")
L.append("`ifndef END_TIME")
L.append("`define END_TIME 200000")
L.append("`endif")
L.append("module wide;")
L.append("  reg clk;")
for i in range(n):
    L.append(f"  reg [31:0] l{i}, a{i};")
    L.append(f"  wire [31:0] m{i}_0, m{i}_1, m{i}_2, m{i}_3;")
for i in range(n):
    L.append(f"  assign m{i}_0 = l{i} ^ (a{i} >> 3);")
    L.append(f"  assign m{i}_1 = m{i}_0 + {{m{i}_0[7:0], m{i}_0[31:8]}};")
    L.append(f"  assign m{i}_2 = m{i}_1 ^ (m{i}_1 << 5) ^ 32'h9e3779b9;")
    L.append(f"  assign m{i}_3 = m{i}_2 - (m{i}_2 >> 11);")
for i in range(n):
    L.append("  always @(posedge clk) begin")
    L.append(f"    l{i} <= {{l{i}[30:0], l{i}[31] ^ l{i}[21] ^ l{i}[1] ^ l{i}[0]}};")
    L.append(f"    if (m{i}_3[0]) a{i} <= a{i} + m{i}_3;")
    L.append(f"    else a{i} <= a{i} ^ m{i}_3;")
    L.append("  end")
L.append("  always #5 clk = ~clk;")
L.append("  initial begin")
for i in range(n):
    L.append(f"    l{i} = 32'd{(0x1234567 + i * 7919) & 0xffffffff}; a{i} = 32'd{i};")
L.append("    clk = 0;")
L.append("    #`END_TIME")
L.append("    $display(\"checksum=%d\", " + " ^ ".join(f"a{i}" for i in range(n)) + ");")
L.append("    $finish;")
L.append("  end")
L.append("endmodule")
print("\n".join(L))
