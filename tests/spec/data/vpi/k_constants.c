static PLI_INT32 check(PLI_BYTE8 *ud) {
    (void)ud;
    int n = (int)(sizeof tab / sizeof tab[0]), wrong = 0;
    for (int i = 0; i < n; i++)
        if (tab[i].have != tab[i].want) {
            vpi_printf("%s is %lld, the standard says %lld\n", tab[i].name, tab[i].have, tab[i].want);
            wrong++;
        }
    vpi_printf("vpi_user.h: %d constants, %d wrong\n", n, wrong);
    return 0;
}

static void boot(void) {
    s_vpi_systf_data d;
    memset(&d, 0, sizeof d);
    d.type = vpiSysTask;
    d.tfname = "$check_k";
    d.calltf = check;
    vpi_register_systf(&d);
}

void (*vlog_startup_routines[])(void) = {boot, 0};
