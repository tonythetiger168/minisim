module counter (clk, rst_n, en, q, carry, one);
  input clk;
  input rst_n;
  input en;
  output [3:0] q;
  output carry;
  output one;
  wire \s[0] ;
  wire \c[1] ;
  wire \s[1] ;
  wire \c[2] ;
  wire \s[2] ;
  wire \c[3] ;
  wire \s[3] ;
  wire \1'b0 ;
  wire \d[0] ;
  wire \d[1] ;
  wire \d[2] ;
  wire \d[3] ;
  XOR2 \ha0/u_s  (.A(q[0]), .B(en), .Y(\s[0] ));
  AND2 \ha0/u_c  (.A(q[0]), .B(en), .Y(\c[1] ));
  XOR2 \ha1/u_s  (.A(q[1]), .B(\c[1] ), .Y(\s[1] ));
  AND2 \ha1/u_c  (.A(q[1]), .B(\c[1] ), .Y(\c[2] ));
  XOR2 \ha2/u_s  (.A(q[2]), .B(\c[2] ), .Y(\s[2] ));
  AND2 \ha2/u_c  (.A(q[2]), .B(\c[2] ), .Y(\c[3] ));
  XOR2 \ha3/u_s  (.A(q[3]), .B(\c[3] ), .Y(\s[3] ));
  AND2 \ha3/u_c  (.A(q[3]), .B(\c[3] ), .Y(carry));
  MUX2 m0 (.A(\s[0] ), .B(\1'b0 ), .S(\1'b0 ), .Y(\d[0] ));
  BUF b1 (.A(\s[1] ), .Y(\d[1] ));
  BUF b2 (.A(\s[2] ), .Y(\d[2] ));
  BUF b3 (.A(\s[3] ), .Y(\d[3] ));
  DFFR r0 (.D(\d[0] ), .CK(clk), .RN(rst_n), .Q(q[0]));
  DFFR r1 (.D(\d[1] ), .CK(clk), .RN(rst_n), .Q(q[1]));
  DFFR r2 (.D(\d[2] ), .CK(clk), .RN(rst_n), .Q(q[2]));
  DFFR r3 (.D(\d[3] ), .CK(clk), .RN(rst_n), .Q(q[3]));
  TIE1 mpnr_tiehi (.Y(one));
  TIE0 mpnr_tielo (.Y(\1'b0 ));
  FILL2 FILLER_0 ();
  FILL1 FILLER_1 ();
  FILL2 FILLER_2 ();
  FILL1 FILLER_3 ();
  FILL2 FILLER_4 ();
  FILL1 FILLER_5 ();
  FILL4 FILLER_6 ();
  FILL4 FILLER_7 ();
  FILL2 FILLER_8 ();
  FILL1 FILLER_9 ();
  FILL1 FILLER_10 ();
  FILL2 FILLER_11 ();
  FILL1 FILLER_12 ();
  FILL1 FILLER_13 ();
  FILL4 FILLER_14 ();
  FILL2 FILLER_15 ();
  FILL4 FILLER_16 ();
  FILL4 FILLER_17 ();
  FILL4 FILLER_18 ();
  FILL2 FILLER_19 ();
  FILL1 FILLER_20 ();
  FILL2 FILLER_21 ();
  FILL1 FILLER_22 ();
  FILL2 FILLER_23 ();
  FILL1 FILLER_24 ();
  FILL1 FILLER_25 ();
  FILL2 FILLER_26 ();
  FILL1 FILLER_27 ();
  FILL1 FILLER_28 ();
  FILL1 FILLER_29 ();
  FILL4 FILLER_30 ();
endmodule
