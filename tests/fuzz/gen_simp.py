#!/usr/bin/env python3
"""tests/fuzz/gen_simp.py - random designs full of the shapes that
src/exprsimp.hpp rewrites (msim -compile only).

Each expression is built from patterns with a known identity: a & '1,
a | '0, a ^ '1, a & '0, ~~a, a & a, a | (a & b), c ? a : a, c ? 1 : 0,
1 && a, 0 || a, !!a, shifts by 0, whole and nested slices, slices of
concatenations, neighbouring slices, resizes to the same width. Operands
take values with x and z bits, so a rule that is only true in 2-valued
logic, or that turns a z into x (or back), shows up as a difference
between the interpreter (which never simplifies) and -compile.
tests/msim_simp.cmake runs both and compares.

    gen_simp.py [seed] [assigns] > simp_<seed>.sv
"""
import random
import sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
nasg = int(sys.argv[2]) if len(sys.argv) > 2 else 80
R = random.Random(seed)
W = [1, 4, 8, 13, 32, 64]
ops = [(f"a{i}", R.choice(W), R.random() < 0.3) for i in range(8)]


def ones(w, s=False):
    return f"{w}'{'s' if s else ''}b" + "1" * w


def zeros(w, s=False):
    return f"{w}'{'s' if s else ''}b" + "0" * w


def leaf():
    n, w, s = R.choice(ops)
    if R.random() < 0.3 and w > 2:
        hi = R.randrange(1, w)
        lo = R.randrange(0, hi)
        return f"{n}[{hi}:{lo}]", hi - lo + 1, False
    return n, w, s


# Returns (text, width, signed). Operands of a binary op get the same width
# (as the lowerer would give them after its resizes) by sizing one to the other.
def same_w(a, b):
    (ta, wa, sa), (tb, wb, sb) = a, b
    if wa == wb:
        return a, b
    w = max(wa, wb)
    if wa < w:
        ta = f"{w}'({ta})"
    if wb < w:
        tb = f"{w}'({tb})"
    return (ta, w, sa), (tb, w, sb)


def expr(d):
    if d <= 0 or R.random() < 0.15:
        return leaf()
    k = R.randrange(20)
    a = expr(d - 1)
    t, w, s = a
    if k == 0: return f"({t} & {ones(w, s)})", w, s
    if k == 1: return f"({zeros(w, s)} | {t})", w, s
    if k == 2: return f"({t} ^ {ones(w, s)})", w, s
    if k == 3: return f"({t} & {zeros(w, s)})", w, s
    if k == 4: return f"({ones(w, s)} | {t})", w, s
    if k == 5: return f"(~(~{t}))", w, s
    if k == 6: return f"({t} {R.choice(['&', '|'])} {t})", w, s
    if k == 7:
        (ta, w2, sa), (tb, _, sb) = same_w(a, expr(d - 1))
        if R.random() < 0.5:
            return f"({ta} | ({ta} & {tb}))", w2, sa and sb
        return f"(({tb} | {ta}) & {ta})", w2, sa and sb
    if k == 8:
        c = expr(d - 1)[0]
        return f"({c} ? {t} : {t})", w, s
    if k == 9:
        c = expr(d - 1)[0]
        return f"((|{c}) ? 1'b1 : 1'b0)" if R.random() < 0.5 else f"((|{c}) ? 1'b0 : 1'b1)", 1, False
    if k == 10: return f"(1'b1 && {t})", 1, False
    if k == 11: return f"({t} || 1'b0)", 1, False
    if k == 12: return f"(!(!{t}))", 1, False
    if k == 13: return f"({t} {R.choice(['<<', '>>', '>>>'])} 0)", w, s
    if k == 14: return f"(1'b0 && {t})", 1, False
    if k == 15: return f"({t} || 1'b1)", 1, False
    if k == 16 and w > 1:
        # nested and whole slices of a named operand
        n, nw, _ = R.choice(ops)
        if nw < 4:
            return f"{n}[{nw - 1}:0]", nw, False
        hi = R.randrange(2, nw)
        lo = R.randrange(0, hi - 1)
        m = R.randrange(lo, hi)
        return f"{{{n}[{hi}:{m + 1}], {n}[{m}:{lo}]}}", hi - lo + 1, False
    if k == 17:
        b = expr(d - 1)
        if w + b[1] <= 64:
            # a slice inside one part of a concatenation
            return f"{{{t}, {b[0]}}}", w + b[1], False
        return a
    if k == 18: return f"(^({t} & {ones(w, s)}))", 1, False
    return f"{'$signed' if s else '$unsigned'}({t})", w, s


L = [f"// tests/fuzz/simp_{seed}.sv - generated by tests/fuzz/gen_simp.py {seed} {nasg}. Do not edit.",
     "module simp;", "  reg clk;"]
for n, w, s in ops:
    L.append(f"  reg {'signed ' if s else ''}[{w - 1}:0] {n};")
res = []
for i in range(nasg):
    t, w, s = expr(R.randrange(1, 4))
    t = f"{t} ^ {R.choice(ops)[0]}" if R.random() < 0.3 else t
    kind = R.randrange(3)
    ow = R.choice(W)
    sg = "signed " if R.random() < 0.3 else ""
    if kind == 0:
        L.append(f"  wire {sg}[{ow - 1}:0] r{i} = {t};")
    elif kind == 1:
        L.append(f"  reg {sg}[{ow - 1}:0] r{i};")
        L.append(f"  always @* r{i} = {t};")
    else:
        L.append(f"  reg {sg}[{ow - 1}:0] r{i};")
        L.append(f"  always @(posedge clk) r{i} <= {t};")
    res.append(f"r{i}")
L.append("  initial begin")
L.append("    clk = 0;")
# Known values first: at time 0 the interpreter wakes @* blocks on an x to x
# write and -compile does not (a known difference, not one of this test's).
for n, w, s in ops:
    L.append(f"    {n} = 0;")
L.append("    #1;")
for step in range(24):
    for n, w, s in ops:
        if R.random() < 0.5:
            pool = "01xz" if R.random() < 0.6 else "01x"
            digits = "".join(R.choice(pool) if R.random() < 0.3 else R.choice("01") for _ in range(w))
            L.append(f"    {n} = {w}'b{digits};")
        else:
            L.append(f"    {n} = {w}'d{R.getrandbits(w)};")
    L.append("    #1 clk = 1;")
    L.append("    #1 clk = 0;")
    for i in range(0, len(res), 6):
        chunk = res[i:i + 6]
        L.append(f"    $display(\"{step} " + " ".join("%b" for _ in chunk) + "\", " + ", ".join(chunk) + ");")
L.append("  end")
L.append("endmodule")
print("\n".join(L))
