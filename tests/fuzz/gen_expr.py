#!/usr/bin/env python3
"""tests/fuzz/gen_expr.py - random expression test for msim -compile.

Writes a module with random continuous assigns and always blocks over
signed and unsigned operands of mixed widths, then drives the operands
through random values (some with x and z bits) and prints every result
with %b. msim -compile has a 2-state fast path (codegen.hpp fast()) that
must give exactly the 4-state result whenever no operand has x or z, and
step aside when one does; tests/msim_compile.cmake compares this design's
output across the interpreter and -compile.

    gen_expr.py [seed] [assigns] > expr_<seed>.sv
"""
import random
import sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
nasg = int(sys.argv[2]) if len(sys.argv) > 2 else 60
R = random.Random(seed)
W = [1, 3, 4, 8, 13, 31, 32, 47, 64]
ops = []
for i in range(8):
    ops.append((f"a{i}", R.choice(W), R.random() < 0.4))

def lit():
    w = R.choice(W)
    if R.random() < 0.7:
        return f"{w}'d{R.getrandbits(w)}", w
    return f"{w}'sd{R.getrandbits(w - 1) if w > 1 else 0}", w

# Each expression comes with its self-determined width, so a concatenation
# never goes past the 64 bits msim supports.
def expr(d):
    if d <= 0 or R.random() < 0.2:
        if R.random() < 0.8:
            n, w, s = R.choice(ops)
            if w > 2 and R.random() < 0.2:
                hi = R.randrange(1, w)
                lo = R.randrange(0, hi)
                return f"{n}[{hi}:{lo}]", hi - lo + 1
            return n, w
        return lit()
    k = R.randrange(11)
    (a, wa), (b, wb) = expr(d - 1), expr(d - 1)
    m = max(wa, wb)
    if k == 0: return f"({a} {R.choice(['+', '-', '*'])} {b})", m
    if k == 1: return f"({a} {R.choice(['&', '|', '^', '~^'])} {b})", m
    if k == 2: return f"({a} {R.choice(['==', '!=', '<', '<=', '>', '>=', '===', '!=='])} {b})", 1
    if k == 3: return f"({a} {R.choice(['<<', '>>', '>>>', '<<<'])} {R.randrange(0, 70)})", wa
    if k == 4:
        o = R.choice(['~', '!', '&', '|', '^', '-'])
        return f"({o}{a})", (wa if o in '~-' else 1)
    if k == 5: return f"({a} {R.choice(['&&', '||'])} {b})", 1
    if k == 6: return f"({expr(d - 1)[0]} ? {a} : {b})", m
    if k == 7 and wa + wb <= 64: return f"{{{a}, {b}}}", wa + wb
    if k == 8: return f"{R.choice(['$signed', '$unsigned'])}({a})", wa
    if k == 9: return f"({a} {R.choice(['<<', '>>', '>>>'])} {b})", wa
    return f"({a} + {b})", m

L = [f"// tests/fuzz/expr_{seed}.sv - generated by tests/fuzz/gen_expr.py {seed} {nasg}. Do not edit.",
     "module fuzz;"]
for n, w, s in ops:
    L.append(f"  reg {'signed ' if s else ''}[{w - 1}:0] {n};")
res = []
for i in range(nasg):
    w = R.choice(W)
    s = R.random() < 0.4
    e = expr(R.randrange(1, 4))[0]
    e = f"{e} ^ {R.choice(ops)[0]}"  # always reads a signal (@* needs one)
    kind = R.randrange(3)
    if kind == 0:
        L.append(f"  wire {'signed ' if s else ''}[{w - 1}:0] r{i} = {e};")
    elif kind == 1:
        L.append(f"  reg {'signed ' if s else ''}[{w - 1}:0] r{i};")
        L.append(f"  always @* r{i} = {e};")
    else:
        L.append(f"  reg {'signed ' if s else ''}[{w - 1}:0] r{i};")
        L.append(f"  always @(posedge clk) r{i} <= {e};")
    res.append(f"r{i}")
L.insert(2, "  reg clk;")
L.append("  initial begin")
L.append("    clk = 0;")
for step in range(24):
    for n, w, s in ops:
        if R.random() < 0.3:
            # Half of these have x but no z: codegen.hpp's two-word path
            # (fx4) takes them; with a z the Val code does.
            pool = "01xz" if R.random() < 0.5 else "01x"
            digits = "".join(R.choice(pool) if R.random() < 0.3 else R.choice("01") for _ in range(w))
            L.append(f"    {n} = {w}'b{digits};")
        else:
            L.append(f"    {n} = {w}'d{R.getrandbits(w)};")
    L.append("    #1 clk = 1;")
    L.append("    #1 clk = 0;")
    for i in range(0, len(res), 6):
        chunk = res[i:i + 6]
        L.append(f"    $display(\"{step} " + " ".join("%b" for _ in chunk) + "\", " + ", ".join(chunk) + ");")
L.append("  end")
L.append("endmodule")
print("\n".join(L))
