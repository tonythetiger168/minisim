// alu_rtl.sv after synthesis, by hand: ripple-carry adder, a mux tree per bit,
// DFFR flops named the way synthesis names them (y_reg_N_).
module alu (input clk, rst_n, input [3:0] a, b, input [1:0] op, output [3:0] y, output zero);
  wire [3:0] s, an, xr, na, m0, m1, r;
  wire [4:0] c;
  wire z01, z23, nz;
  TIE0 t0 (.Y(c[0]));
  XOR2 x0 (.A(a[0]), .B(b[0]), .Y(xr[0]));
  XOR2 sx0 (.A(xr[0]), .B(c[0]), .Y(s[0]));
  AND2 g0 (.A(a[0]), .B(b[0]), .Y(an[0]));
  wire p0; AND2 pc0 (.A(xr[0]), .B(c[0]), .Y(p0));
  OR2 co0 (.A(an[0]), .B(p0), .Y(c[1]));
  INV n0 (.A(a[0]), .Y(na[0]));
  MUX2 ma0 (.A(s[0]), .B(an[0]), .S(op[0]), .Y(m0[0]));
  MUX2 mb0 (.A(xr[0]), .B(na[0]), .S(op[0]), .Y(m1[0]));
  MUX2 mc0 (.A(m0[0]), .B(m1[0]), .S(op[1]), .Y(r[0]));
  DFFR y_reg_0_ (.D(r[0]), .CK(clk), .RN(rst_n), .Q(y[0]));
  XOR2 x1 (.A(a[1]), .B(b[1]), .Y(xr[1]));
  XOR2 sx1 (.A(xr[1]), .B(c[1]), .Y(s[1]));
  AND2 g1 (.A(a[1]), .B(b[1]), .Y(an[1]));
  wire p1; AND2 pc1 (.A(xr[1]), .B(c[1]), .Y(p1));
  OR2 co1 (.A(an[1]), .B(p1), .Y(c[2]));
  INV n1 (.A(a[1]), .Y(na[1]));
  MUX2 ma1 (.A(s[1]), .B(an[1]), .S(op[0]), .Y(m0[1]));
  MUX2 mb1 (.A(xr[1]), .B(na[1]), .S(op[0]), .Y(m1[1]));
  MUX2 mc1 (.A(m0[1]), .B(m1[1]), .S(op[1]), .Y(r[1]));
  DFFR y_reg_1_ (.D(r[1]), .CK(clk), .RN(rst_n), .Q(y[1]));
  XOR2 x2 (.A(a[2]), .B(b[2]), .Y(xr[2]));
  XOR2 sx2 (.A(xr[2]), .B(c[2]), .Y(s[2]));
  AND2 g2 (.A(a[2]), .B(b[2]), .Y(an[2]));
  wire p2; AND2 pc2 (.A(xr[2]), .B(c[2]), .Y(p2));
  OR2 co2 (.A(an[2]), .B(p2), .Y(c[3]));
  INV n2 (.A(a[2]), .Y(na[2]));
  MUX2 ma2 (.A(s[2]), .B(an[2]), .S(op[0]), .Y(m0[2]));
  MUX2 mb2 (.A(xr[2]), .B(na[2]), .S(op[0]), .Y(m1[2]));
  MUX2 mc2 (.A(m0[2]), .B(m1[2]), .S(op[1]), .Y(r[2]));
  DFFR y_reg_2_ (.D(r[2]), .CK(clk), .RN(rst_n), .Q(y[2]));
  XOR2 x3 (.A(a[3]), .B(b[3]), .Y(xr[3]));
  XOR2 sx3 (.A(xr[3]), .B(c[3]), .Y(s[3]));
  AND2 g3 (.A(a[3]), .B(b[3]), .Y(an[3]));
  wire p3; AND2 pc3 (.A(xr[3]), .B(c[3]), .Y(p3));
  OR2 co3 (.A(an[3]), .B(p3), .Y(c[4]));
  INV n3 (.A(a[3]), .Y(na[3]));
  MUX2 ma3 (.A(s[3]), .B(an[3]), .S(op[0]), .Y(m0[3]));
  MUX2 mb3 (.A(xr[3]), .B(na[3]), .S(op[0]), .Y(m1[3]));
  MUX2 mc3 (.A(m0[3]), .B(m1[3]), .S(op[1]), .Y(r[3]));
  DFFR y_reg_3_ (.D(r[3]), .CK(clk), .RN(rst_n), .Q(y[3]));
  NOR2 z0 (.A(y[0]), .B(y[1]), .Y(z01));
  NOR2 z1 (.A(y[2]), .B(y[3]), .Y(z23));
  AND2 z2 (.A(z01), .B(z23), .Y(zero));
endmodule
