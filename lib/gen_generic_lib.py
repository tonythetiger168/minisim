#!/usr/bin/env python3
"""Writes lib/msynth_generic.lib: the small generic cell library msynth maps
to when no target library is given. Every table is linear in its indexes:

  cell_rise = d0 + 0.3*slew + 2.0*load       cell_fall = 0.9*d0 + 0.3*slew + 1.8*load
  rise_transition = 0.02 + 0.1*slew + 3.0*load   fall_transition = 0.02 + 0.1*slew + 2.5*load

Times in ns, capacitances in pF, area in arbitrary units (INV = 1).
Run:  python3 lib/gen_generic_lib.py > lib/msynth_generic.lib
"""
import itertools

SLEW = [0.01, 0.1, 0.5]
LOAD = [0.001, 0.01, 0.1]

def table(name, f, ind="        "):
    rows = []
    for s in SLEW:
        rows.append('"' + ", ".join("%.5f" % f(s, l) for l in LOAD) + '"')
    return "%s%s (delay_3x3) {\n%s  values (%s);\n%s}\n" % (ind, name, ind, (", \\\n" + ind + "          ").join(rows), ind)

def arcs(d0, ind="        "):
    return (table("cell_rise", lambda s, l: d0 + 0.3 * s + 2.0 * l, ind) +
            table("cell_fall", lambda s, l: 0.9 * d0 + 0.3 * s + 1.8 * l, ind) +
            table("rise_transition", lambda s, l: 0.02 + 0.1 * s + 3.0 * l, ind) +
            table("fall_transition", lambda s, l: 0.02 + 0.1 * s + 2.5 * l, ind))

def pyexpr(fn):
    return fn.replace("!", " not ").replace("&", " and ").replace("|", " or ").replace("^", " != ")

def sense(fn, pins, p):
    pos = neg = False
    others = [q for q in pins if q != p]
    for vals in itertools.product([False, True], repeat=len(others)):
        env = dict(zip(others, vals))
        lo = eval(pyexpr(fn), {}, dict(env, **{p: False}))
        hi = eval(pyexpr(fn), {}, dict(env, **{p: True}))
        if hi and not lo: pos = True
        if lo and not hi: neg = True
    return "non_unate" if pos and neg else "negative_unate" if neg else "positive_unate"

COMB = [
    # name, area, d0, pins, function, input cap
    ("INV", 1.0, 0.020, "A", "!A"),
    ("BUF", 1.5, 0.040, "A", "A"),
    ("NAND2", 1.5, 0.025, "AB", "!(A&B)"),
    ("NOR2", 1.5, 0.030, "AB", "!(A|B)"),
    ("AND2", 2.0, 0.045, "AB", "A&B"),
    ("OR2", 2.0, 0.050, "AB", "A|B"),
    ("NAND3", 2.0, 0.035, "ABC", "!(A&B&C)"),
    ("NOR3", 2.0, 0.045, "ABC", "!(A|B|C)"),
    ("AND3", 2.5, 0.055, "ABC", "A&B&C"),
    ("OR3", 2.5, 0.060, "ABC", "A|B|C"),
    ("NAND4", 2.5, 0.045, "ABCD", "!(A&B&C&D)"),
    ("NOR4", 2.5, 0.060, "ABCD", "!(A|B|C|D)"),
    ("AND4", 3.0, 0.065, "ABCD", "A&B&C&D"),
    ("OR4", 3.0, 0.070, "ABCD", "A|B|C|D"),
    ("XOR2", 3.0, 0.060, "AB", "A^B"),
    ("XNOR2", 3.0, 0.060, "AB", "!(A^B)"),
    ("MUX2", 3.5, 0.065, "ABS", "(A&!S)|(B&S)"),
    ("AOI21", 2.0, 0.035, "ABC", "!((A&B)|C)"),
    ("OAI21", 2.0, 0.035, "ABC", "!((A|B)&C)"),
    ("AOI22", 2.5, 0.040, "ABCD", "!((A&B)|(C&D))"),
    ("OAI22", 2.5, 0.040, "ABCD", "!((A|B)&(C|D))"),
]

out = []
out.append("""/* msynth's generic cell library: the default target when a script names
   none. Generated by lib/gen_generic_lib.py; do not edit by hand.
   Times in ns, capacitances in pF, area in units of one inverter. */
library (msynth_generic) {
  delay_model : table_lookup;
  time_unit : "1ns";
  capacitive_load_unit (1, pf);
  voltage_unit : "1V";
  current_unit : "1mA";
  leakage_power_unit : "1nW";
  pulling_resistance_unit : "1kohm";
  nom_process : 1;
  nom_voltage : 1.0;
  nom_temperature : 25;
  default_max_transition : 1.0;
  lu_table_template (delay_3x3) {
    variable_1 : input_net_transition;
    variable_2 : total_output_net_capacitance;
    index_1 ("0.01, 0.1, 0.5");
    index_2 ("0.001, 0.01, 0.1");
  }
  lu_table_template (cons_3x3) {
    variable_1 : related_pin_transition;
    variable_2 : constrained_pin_transition;
    index_1 ("0.01, 0.1, 0.5");
    index_2 ("0.01, 0.1, 0.5");
  }
""")
for name, area, d0, pins, fn in COMB:
    cap = 0.003 if "XOR" in name or "XNOR" in name or name == "MUX2" else 0.002
    s = "  cell (%s) {\n    area : %g;\n    cell_leakage_power : %g;\n" % (name, area, area)
    for p in pins:
        s += "    pin (%s) { direction : input; capacitance : %g; }\n" % (p, cap)
    s += '    pin (Y) {\n      direction : output;\n      function : "%s";\n      max_capacitance : 0.2;\n' % fn
    for k, p in enumerate(pins):
        s += '      timing () {\n        related_pin : "%s";\n        timing_sense : %s;\n' % (p, sense(fn, list(pins), p))
        s += arcs(d0 + 0.003 * k)
        s += "      }\n"
    s += "    }\n  }\n"
    out.append(s)
for name, fn in (("TIE0", "0"), ("TIE1", "1")):
    out.append('  cell (%s) {\n    area : 1;\n    pin (Y) { direction : output; function : "%s"; }\n  }\n' % (name, fn))

def cons(name, base, ind="        "):
    rows = []
    for c in SLEW:
        rows.append('"' + ", ".join("%.5f" % (base + 0.1 * d + 0.05 * c) for d in SLEW) + '"')
    return "%s%s (cons_3x3) {\n%s  values (%s);\n%s}\n" % (ind, name, ind, (", \\\n" + ind + "          ").join(rows), ind)

for name, area, extra in (("DFF", 6.0, None), ("DFFR", 7.0, "RN"), ("DFFS", 7.0, "SN")):
    s = "  cell (%s) {\n    area : %g;\n    cell_leakage_power : %g;\n" % (name, area, area)
    s += '    ff (IQ, IQN) {\n      clocked_on : "CK";\n      next_state : "D";\n'
    if extra == "RN": s += '      clear : "!RN";\n'
    if extra == "SN": s += '      preset : "!SN";\n'
    s += "    }\n"
    s += "    pin (D) {\n      direction : input;\n      capacitance : 0.002;\n"
    for tt, base in (("setup_rising", 0.04), ("hold_rising", 0.01)):
        s += '      timing () {\n        related_pin : "CK";\n        timing_type : %s;\n' % tt
        s += cons("rise_constraint", base) + cons("fall_constraint", base)
        s += "      }\n"
    s += "    }\n"
    s += "    pin (CK) { direction : input; capacitance : 0.002; clock : true; }\n"
    if extra:
        s += "    pin (%s) {\n      direction : input;\n      capacitance : 0.002;\n" % extra
        for tt, base in (("recovery_rising", 0.03), ("removal_rising", 0.01)):
            s += '      timing () {\n        related_pin : "CK";\n        timing_type : %s;\n' % tt
            s += cons("rise_constraint", base)
            s += "      }\n"
        s += "    }\n"
    s += '    pin (Q) {\n      direction : output;\n      function : "IQ";\n      max_capacitance : 0.2;\n'
    s += '      timing () {\n        related_pin : "CK";\n        timing_type : rising_edge;\n        timing_sense : non_unate;\n'
    s += arcs(0.10)
    s += "      }\n"
    if extra:
        kind = "clear" if extra == "RN" else "preset"
        s += '      timing () {\n        related_pin : "%s";\n        timing_type : %s;\n        timing_sense : %s;\n' % (
            extra, kind, "positive_unate" if extra == "RN" else "negative_unate")
        if extra == "RN":
            s += table("cell_fall", lambda sl, l: 0.08 + 0.3 * sl + 1.8 * l) + table("fall_transition", lambda sl, l: 0.02 + 0.1 * sl + 2.5 * l)
        else:
            s += table("cell_rise", lambda sl, l: 0.08 + 0.3 * sl + 2.0 * l) + table("rise_transition", lambda sl, l: 0.02 + 0.1 * sl + 3.0 * l)
        s += "      }\n"
    s += "    }\n  }\n"
    out.append(s)
out.append("}\n")
print("".join(out), end="")
